function createAnalyticsHistory(): Appointment[] {
  const result: Appointment[] = [];
  const endDate = new Date("2026-10-18T12:00:00Z");

  for (let dayOffset = 0; dayOffset < 90; dayOffset += 1) {
    const date = new Date(endDate);
    date.setUTCDate(date.getUTCDate() - dayOffset);
    const dateValue = date.toISOString().slice(0, 10);
    const bookingsPerDay = 6 + (dayOffset % 4);

    for (let bookingIndex = 0; bookingIndex < bookingsPerDay; bookingIndex += 1) {
      const sequence = dayOffset * 3 + bookingIndex;
      const master = analyticsMasterServices[(dayOffset + bookingIndex) % analyticsMasterServices.length];
      const serviceId = master.serviceIds[sequence % master.serviceIds.length];
      const startHour = 9 + bookingIndex;
      const isCancelled =
        (dayOffset < 7 &&
          ((dayOffset === 3 && bookingIndex === 0) ||
            (dayOffset === 6 && bookingIndex === 1))) ||
        (dayOffset >= 7 &&
          dayOffset < 30 &&
          dayOffset % 3 === 0 &&
          bookingIndex === 0) ||
        (dayOffset >= 30 &&
          dayOffset % 3 === 0 &&
          bookingIndex < 2);
      const status: Appointment["status"] = isCancelled
        ? "cancelled"
        : sequence % 11 === 0
          ? "pending"
          : "paid";

      result.push({
        id: `analytics-${dateValue}-${bookingIndex}`,
        clientId: `client-${String((sequence % 18) + 1).padStart(2, "0")}`,
        masterId: master.masterId,
        serviceId,
        date: dateValue,
        startTime: `${String(startHour).padStart(2, "0")}:00`,
        endTime: `${String(startHour + 1).padStart(2, "0")}:00`,
        status,
        depositPaid: status === "paid",
        notes: "",
      });
    }
  }

  return result;
}

